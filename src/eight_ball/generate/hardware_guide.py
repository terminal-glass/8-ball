"""Readable hardware tables derived from the committed data, never a second catalog."""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any


def cell(value: Any) -> str:
    if value is None or value == "":
        return "Unknown"
    if isinstance(value, bool):
        return "Yes" if value else "No"
    text = f"{value:g}" if isinstance(value, (int, float)) else str(value)
    return text.replace("|", r"\|").replace("\n", " ")


def table(headers: list[str], rows: list[list[Any]]) -> list[str]:
    return [
        "| " + " | ".join(headers) + " |",
        "| " + " | ".join("---" for _ in headers) + " |",
        *("| " + " | ".join(cell(value) for value in row) + " |" for row in rows),
        "",
    ]


def source_link(record: dict[str, Any]) -> str:
    source = record.get("source_file")
    if not source:
        return "Unknown"
    row = record.get("source_row")
    label = f"Source row {row}" if row is not None else "Source"
    return f"[{label}](../{source})"


def render_hardware_guide(root: Path) -> str:
    def read(path: str) -> Any:
        return json.loads((root / path).read_text(encoding="utf-8"))

    assumed = read("data/normalized/hardware-assumed-profiles.json")
    measured = read("data/normalized/hardware-measured-hosts.json")
    providers = read("data/normalized/hardware-provider-instances.json")
    accelerators = read("data/normalized/hardware-accelerator-classes.json")
    lanes = read("profiles/lanes.json")["lanes"]
    counts = read("profiles/manifest.json")["counts"]

    lines = [
        "<!-- Generated by scripts/generate-hardware-guide.py. Edit the linked source data, then regenerate. -->",
        "",
        "# Hardware profiles",
        "",
        "Start here to browse the hardware behind 8-BALL model recommendations.",
        "This page reads existing normalized records and the canonical profile matrix; it is not another source of truth.",
        "",
        ("[Planning profiles](#planning-profiles) · [Measured hosts](#measured-hosts) · "
        "[Provider plans](#provider-plans) · [Runtime lanes](#runtime-lanes) · [Data and updates](#data-and-updates)"),
        "",
        "## Read the evidence correctly",
        "",
        "- **Planning profiles** are assumptions, not benchmarks of your computer.",
        "- **Measured hosts** record hardware observations; inference verification is shown separately.",
        "- **Provider plans** are committed snapshots, not live availability or price quotes.",
        "- **Unknown** means the source did not establish the value; it is never silently replaced with zero.",
        ("- RAM, model-usable RAM, VRAM, and download size are different quantities. "
        "Unified memory is not added to system RAM as a second pool."),
        ("- Capacities below preserve the source fields' GB labels. "
        "The source records retain original units, notes, ranges, and provenance."),
        "",
        "## Planning profiles",
        "",
        (f"{len(assumed)} imported planning profiles. "
        "Read [the JSON](../data/normalized/hardware-assumed-profiles.json) for full limits and notes."),
        "",
    ]
    lines += table(
        ["Profile ID", "Description", "RAM GB", "Model-usable RAM GB", "Total VRAM GB", "Evidence"],
        [
            [
                r.get("profile_id"),
                r.get("display_name"),
                r.get("system_ram_gb"),
                r.get("usable_model_ram_gb"),
                r.get("total_vram_gb"),
                source_link(r),
            ]
            for r in sorted(assumed, key=lambda r: r["profile_id"])
        ],
    )
    lines += [
        "## Measured hosts",
        "",
        (f"{len(measured)} recorded hardware observations. "
        "[Full observations](../data/normalized/hardware-measured-hosts.json)."),
        "",
    ]
    lines += table(
        [
            "Host ID",
            "RAM GB",
            "GPU",
            "Total VRAM GB",
            "Inference verified",
            "Observed at",
            "Evidence",
        ],
        [
            [
                r.get("host_profile_id"),
                r.get("system_ram_gb"),
                r.get("gpu_model"),
                r.get("total_vram_gb"),
                r.get("ollama_inference_verified"),
                r.get("measured_at_utc"),
                source_link(r),
            ]
            for r in sorted(measured, key=lambda r: r["host_profile_id"])
        ],
    )
    lines += [
        "## Provider plans",
        "",
        (f"{len(providers)} provider records. "
        "[Full snapshots](../data/normalized/hardware-provider-instances.json) include source references and limitations."),
        "Rows are identified by provider, product line, and plan ID together.",
        "",
    ]
    lines += table(
        ["Provider", "Product line", "Plan ID", "CPU count", "RAM GB", "Total VRAM GB", "Evidence"],
        [
            [
                r.get("provider"),
                r.get("product_line"),
                r.get("provider_plan_id"),
                r.get("cpu_count"),
                r.get("system_ram_gb"),
                r.get("total_vram_gb"),
                source_link(r),
            ]
            for r in sorted(
                providers, key=lambda r: (r["provider"], r["product_line"], r["provider_plan_id"])
            )
        ],
    )
    lines += [
        "## Accelerator classes",
        "",
        "[Full accelerator records](../data/normalized/hardware-accelerator-classes.json).",
        "",
    ]
    lines += table(
        ["Class ID", "Backend", "Platform scope", "Evidence"],
        [
            [
                r.get("accelerator_class_id"),
                r.get("backend"),
                r.get("platform_scope"),
                source_link(r),
            ]
            for r in sorted(accelerators, key=lambda r: r["accelerator_class_id"])
        ],
    )
    lines += [
        "## Runtime lanes",
        "",
        (f"The canonical matrix contains {counts['models']:,} model entries, "
        f"{counts['distinct_model_sizes']:,} model-size records, and {counts['matrix_rows']:,} "
        f"model-size-lane rows across {len(lanes)} lanes."),
        "A metadata lane does not establish that an installation passed on physical hardware.",
        "Read each lane's documentation for implementation and test status.",
        "",
    ]
    lines += table(
        ["Lane", "Architecture", "Acceleration", "Installer documentation"],
        [
            [
                r["lane_path"],
                r.get("architecture"),
                r.get("acceleration"),
                f"[Read lane](../install/{r['lane_path']}/README.md)",
            ]
            for r in lanes
        ],
    )
    lines += [
        "## Data and updates",
        "",
        "| Need | Start here |",
        "| --- | --- |",
        "| Search the model-size-lane matrix | [profiles/index.csv](../profiles/index.csv) |",
        "| Runtime profile contract | [profiles/README.md](../profiles/README.md) |",
        "| Matrix version and counts | [profiles/manifest.json](../profiles/manifest.json) |",
        "| Lane definitions | [profiles/lanes.json](../profiles/lanes.json) |",
        "| Imported hardware records | [data/normalized](../data/normalized/) |",
        "| Original hardware inputs | [profile-mapping](../AGENTS/data-science/profile-mapping/) |",
        "| Hardware import/provenance audit | [C6 audit](../docs/C6-hardware-data-import-audit.md) |",
        "| Repository navigation and retained history | [Repository layout](../docs/repository-layout.md) |",
        "",
        ("Edit original inputs and use the existing import/profile-generation workflow. "
        "Do not hand-edit this guide or create a competing catalog."),
        "",
        "Regenerate this readable view after the normalized hardware or profile matrix changes:",
        "",
        "```bash",
        "python3 scripts/generate-hardware-guide.py",
        "```",
        "",
        "Check that the committed guide matches its sources without writing files:",
        "",
        "```bash",
        "python3 scripts/generate-hardware-guide.py --check",
        "```",
        "",
    ]
    return "\n".join(lines)
