#!/usr/bin/env python3
"""Build RESULTS-TABLE.md from results/<label>/ (bench.jsonl, cron-*.json, openclaw.json).

Columns are fixed so a pending host shows as a placeholder:
  box-emulated (cgroup on a shared x86 server), real x86 VM, arm64 emulated VM.
"""
import glob, json, os, statistics, sys
here = os.path.dirname(os.path.abspath(__file__))
COLS = [  # (label, heading)
    ("box-emulated-l0-4c-2g", "box-emulated, 4 pinned cores, 2 GiB"),
    ("box-emulated-l0-4c-half-2g", "box-emulated, 4 cores at 50 %, 2 GiB"),
    ("box-emulated-l0-4c-1g", "box-emulated, 4 cores, 1 GiB"),
    ("vm-x86-2c-2g", "real VM, 2 vCPU / 2 GB x86 (not ARM Pi)"),
    ("vm-arm64-2g", "arm64 emulated 2 GB VM"),
]
def load(label):
    rows = []
    for f in sorted(glob.glob(f"{here}/results/{label}/bench*.jsonl")):
        hdr = [l.strip("# \n") for l in open(f) if l.startswith("#")]
        rows += [dict(json.loads(l), _file=os.path.basename(f), _hdr=hdr) for l in open(f) if l.startswith("{")]
    return rows
def cell(rows, model):
    rs = [r for r in rows if r["model"] == model and r.get("_file") == "bench.jsonl"] or [r for r in rows if r["model"] == model]
    if not rs: return "pending"
    ok = [r for r in rs if r["ok"]]
    cold = next((r for r in rs if r["cold"]), None)
    s = f"loaded {len(ok)}/{len(rs)} runs"
    if not ok:
        oom = max((r.get("cgroup_oom_kills") or 0) for r in rs)
        return s + (f"; OOM-killed ({oom}x)" if oom else f"; {rs[0]['error'][:60]}")
    rss = max(r["runner_peak_rss_mb"] or 0 for r in ok)
    tps = [r["eval_tok_s"] for r in ok if r.get("eval_tok_s")]
    s += f"; peak RSS {rss:.0f} MB"
    if cold and cold["ok"]:
        s += f"; cold load {cold['load_s']} s; cold TTFT {cold['ttft_s']} s"
    s += f"; {min(tps):.1f}-{max(tps):.1f} tok/s (median {statistics.median(tps):.1f})"
    return s
def cron(label, model):
    f = f"{here}/results/{label}/cron-{model.replace(':', '_').replace('/', '_')}.json"
    if not os.path.exists(f): return "pending" if label == "vm-arm64-2g" else "not run"
    d = json.load(open(f))
    s = (f"{d['fired']}/{d['expected_runs']} fired, {d['missed']} missed, {d['late']} late >{d['late_over_s']:.0f} s; "
         f"lateness {d['lateness_s_min']}-{d['lateness_s_max']} s")
    gens = d.get("load_generations")
    med = d.get("load_eval_tok_s_median")
    if gens:
        s += f"; load {gens} gens at median {med} tok/s"
    elif d.get("load_model") not in (None, "none"):
        s += "; load 0 gens"
    return s
out = ["# Level-0 results table (generated by summarize.py)", "",
       "| | " + " | ".join(h for _, h in COLS) + " |", "|---" * (len(COLS) + 1) + "|"]
data = {l: load(l) for l, _ in COLS}
for m in ("tinyllama:1.1b", "llama3.2:1b"):
    out.append(f"| `{m}` bench | " + " | ".join(cell(data[l], m) for l, _ in COLS) + " |")
for m in ("tinyllama:1.1b", "llama3.2:1b"):
    out.append(f"| cron, 10 min under `{m}` load | " + " | ".join(cron(l, m) for l, _ in COLS) + " |")
oc = []
for l, _ in COLS:
    f = f"{here}/results/{l}/openclaw.json"
    if os.path.exists(f):
        d = json.load(open(f))
        ready = d.get("gateway_ready_s")
        ready_s = "never" if ready is None else f"{ready} s"
        oc.append(f"gateway ready {ready_s}; RSS idle {d['gateway_rss_mb_idle']} MB, peak {d['gateway_rss_mb_peak']} MB; "
                  f"consult: {d['consult_error'] or 'exit ' + str(d['consult_exit'])}")
    else:
        oc.append("pending" if l == "vm-arm64-2g" else "not run")
out.append("| OpenClaw, cloud model only, no Ollama | " + " | ".join(oc) + " |")
out += ["", "Machine facts per column (from result headers):", ""]
for l, h in COLS:
    hdr = data[l][0]["_hdr"] if data[l] else ["pending"]
    out.append(f"- **{h}**: " + " / ".join(hdr))
swap_oc = f"{here}/results/vm-arm64-2g-swap/openclaw.json"
if os.path.exists(swap_oc):
    d = json.load(open(swap_oc))
    ready = d.get("gateway_ready_s")
    ready_s = "never" if ready is None else f"{ready} s"
    cron = d.get("cron") or {}
    out += [
        "",
        "Not a table column: `results/vm-arm64-2g-swap/` is the same arm64 VM with a 2 GB swapfile during the OpenClaw test (not during the model bench). "
        f"OpenClaw: gateway ready {ready_s}; RSS idle {d['gateway_rss_mb_idle']} MB, peak {d['gateway_rss_mb_peak']} MB; "
        f"consult: {d['consult_error'] or 'exit ' + str(d['consult_exit'])} in {d.get('consult_s')} s; "
        f"cron {cron.get('fired')}/{cron.get('expected_runs')} fired, {cron.get('missed')} missed, {cron.get('late')} late "
        f"({cron.get('lateness_s_min')}-{cron.get('lateness_s_max')} s).",
    ]
open(f"{here}/RESULTS-TABLE.md", "w").write("\n".join(out) + "\n")
print("\n".join(out))
